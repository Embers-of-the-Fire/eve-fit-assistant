void main() {
  setUpAll(() async {
    await PathProvider.init();
  });

  test("sqlite3_web opens a preplaced OPFS database and queries it", () async {
    for (final probe in ["", "main.dart.js", "packages/eve_fit_assistant/web/sqlite/sqlite3.wasm", "assets/web/sqlite/sqlite3.wasm", "manifest.json", "assets/AssetManifest.json"]) {
      final resp = await web.window.fetch(probe.toJS).toDart;
      // ignore: avoid_print
      print("PROBE $probe -> ${resp.status} ${resp.headers.get("content-type")}");
    }

    final opfs = OpfsBlobStore.instance;
    await opfs.init();

    final dbName = "localization_probe";
    final dbFilePath = "drift_db/$dbName/database";
    await opfs.deleteTree("drift_db/$dbName");

    final bytes = Uint8List.fromList(base64Decode(_fixtureB64));
    await opfs.write(dbFilePath, bytes);

    // Confirm the blob landed where sqlite3_web expects it.
    expect(await opfs.exists(dbFilePath), isTrue);
    final roundTrip = await opfs.read(dbFilePath);
    expect(roundTrip!.length, bytes.length);
    expect(roundTrip.sublist(0, 16), bytes.sublist(0, 16));

    final db = SqliteDatabase(
      path: dbName,
      options: const SqliteOptions(
        webSqliteOptions: WebSqliteOptions(workerUri: "web/sqlite/db_worker.js"),
      ),
    );

    final meta = await db.getOptional("SELECT value FROM meta WHERE key = 'schema_version'");
    expect(meta?["value"], "1");

    final name = await db.getOptional(
      "SELECT value FROM strings WHERE locale = ? AND id = ?",
      ["zh", 1001],
    );
    expect(name?["value"], "加伦特护卫舰");

    await db.close();
    await opfs.deleteTree("drift_db/$dbName");
  });
}
