"""
Generates the Dart resource-resolution sources from the RRS spec.

Reads ``data/schema/resource_resolution.toml`` (see ``bootstrap.resolution``)
and emits two files:

- ``lib/storage/repo/resource_resolution.g.dart`` — the fixed header
  (``data/schema/resource_resolution.header.dart``, prepended verbatim), the
  ``ResourceResolution`` enum, the RRS version
  (``kResourceResolutionSchemaVersion``, single-sourced from the spec's
  ``version``), the ``ResourceResolutionContext`` class generated from the
  spec's context fields, and the raw ``resolveResource`` evaluator compiled
  from the rule list;
- ``lib/constant/resource_vocabulary.g.dart`` — the shared resource-layout
  vocabulary constants.
"""

from __future__ import annotations

import textwrap

from typing import TYPE_CHECKING

from bootstrap.constant import DART_ROOT
from bootstrap.constant import PROJECT_ROOT
from bootstrap.resolution import ResolutionRule
from bootstrap.resolution import ResolutionSpec
from bootstrap.resolution import resolution_spec
from bootstrap.resolution import split_pattern


if TYPE_CHECKING:
    from pathlib import Path


HEADER_PATH = PROJECT_ROOT / "data" / "schema" / "resource_resolution.header.dart"
VOCABULARY_OUT_PATH = DART_ROOT / "constant" / "resource_vocabulary.g.dart"
RESOLUTION_OUT_PATH = DART_ROOT / "storage" / "repo" / "resource_resolution.g.dart"

_GENERATED_BY = (
    "// Automatically generated by "
    "`bootstrap.data.codegen.resource_resolution.codegen_dart`\n"
    "// DO NOT EDIT\n"
)

#: The resolution enum is a fixed monorepo symbol: the spec's resolution
#: values map onto its variants one-to-one, so the template owns it.
_ENUM_TEMPLATE = """
/// The download decision for a single `ResourceIndex.Entry`, made by the
/// client through the Resource Resolution Schema.
///
/// The resolution **replaces** the server-stamped `download_policy` for new
/// clients; the stamped policy remains meaningful only to older clients and
/// to resolution-less tooling.
enum ResourceResolution {
  /// Downloaded ahead of time during provisioning and data updates. Expected
  /// present; a missing blob is a verification failure subject to repair.
  eager,

  /// Not downloaded ahead of time. Fetched on first access through the
  /// on-demand blob path. A missing blob is expected and never a verification
  /// failure; a present blob is still hash-verified.
  lazy,

  /// Never downloaded and never expected. Invisible to provisioning, updates,
  /// verification, and size previews. Used for superseded resources retained
  /// only for older clients.
  excluded,
}
"""

_VERSION_DOC = """\
/// Version of the Resource Resolution Schema (RRS) shipped with the app.
///
/// The RRS is the app's declarative rule set deciding which checkout
/// resources are downloaded eagerly, lazily, or not at all. The version is a
/// property of the app release (like the per-DB schema versions); it is
/// surfaced on the version settings page but is not persisted into the
/// repository and triggers no migration. Single-sourced from `version` in
/// `data/schema/resource_resolution.toml`; bump it there when the rule list
/// changes in a behaviorally meaningful way.
"""

_CONTEXT_CLASS_DOC = """\
/// Client-side state available to RRS rule evaluation.
///
/// The context is read at the moment of evaluation; provisioning, data
/// updates, and size previews evaluate with the state active at that time.
"""


def _dart_escape(value: str) -> str:
    """Escape a literal for inclusion in a double-quoted Dart string."""
    return value.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$")


def _matcher_description(rule: ResolutionRule, scheme: str) -> str:
    if rule.exact is not None:
        return f"exact `{scheme}{rule.exact}`"
    if rule.prefix is not None:
        return f"prefix `{scheme}{rule.prefix}`"
    assert rule.pattern is not None
    return f"pattern `{scheme}{rule.pattern}`"


def _rule_doc(rule: ResolutionRule, index: int, scheme: str) -> list[str]:
    """One ``- Rn ...`` summary for the function's doc comment, wrapped."""
    matcher = _matcher_description(rule, scheme)
    if rule.resolution is not None:
        if rule.excluded_when_prefix_present is not None:
            outcome = (
                f"excluded when the index contains "
                f"`{scheme}{rule.excluded_when_prefix_present}` entries, "
                f"else {rule.resolution}"
            )
        else:
            outcome = rule.resolution
    else:
        outcome = f"{rule.on_context_match} on context match, {rule.on_context_mismatch} otherwise"
    return textwrap.wrap(
        f"- R{index} {matcher} → {outcome}.",
        width=98,
        initial_indent="/// ",
        subsequent_indent="///   ",
    )


def _rule_body(rule: ResolutionRule, scheme: str) -> list[str]:
    """The Dart statements implementing one rule (first match wins)."""
    if rule.exact is not None:
        condition = f'id == "{_dart_escape(scheme + rule.exact)}"'
        family = None
    elif rule.prefix is not None:
        condition = f'id.startsWith("{_dart_escape(scheme + rule.prefix)}")'
        family = None
    else:
        assert rule.pattern is not None
        head, field, tail = split_pattern(rule.pattern)
        condition = f'id == "{_dart_escape(scheme + head)}${{context.{field}}}{_dart_escape(tail)}"'
        family = f'id.startsWith("{_dart_escape(scheme + head)}")'

    if rule.resolution is not None:
        if rule.excluded_when_prefix_present is not None:
            superseded = _dart_escape(scheme + rule.excluded_when_prefix_present)
            return [
                f"if ({condition}) {{",
                "  final superseded = index.entries.any(",
                f'    (e) => e.resourceId.startsWith("{superseded}"),',
                "  );",
                f"  return superseded ? ResourceResolution.excluded : ResourceResolution.{rule.resolution};",
                "}",
            ]
        return [f"if ({condition}) return ResourceResolution.{rule.resolution};"]
    assert family is not None
    return [
        f"if ({condition}) return ResourceResolution.{rule.on_context_match};",
        f"if ({family}) return ResourceResolution.{rule.on_context_mismatch};",
    ]


def _context_class(spec: ResolutionSpec) -> str:
    lines = [_CONTEXT_CLASS_DOC.rstrip("\n"), "final class ResourceResolutionContext {"]
    parameters = ", ".join(f"required this.{field.name}" for field in spec.context)
    lines.append(f"  const ResourceResolutionContext({{{parameters}}});")
    for field in spec.context:
        lines.append("")
        if field.doc:
            lines.append(f"  /// {field.doc}")
        lines.append(f"  final {field.type} {field.name};")
    lines.append("}")
    return "\n".join(lines)


def _resolve_function(spec: ResolutionSpec) -> str:
    scheme = spec.vocabulary.scheme
    lines = [
        f"/// Evaluates the Resource Resolution Schema (RRS v{spec.version}) for [entry]",
        "/// against [index] and [context], returning the first matching rule's",
        "/// resolution.",
        "///",
        "/// Rules, in order (first match wins):",
    ]
    for i, rule in enumerate(spec.rules, start=1):
        lines.extend(_rule_doc(rule, i, scheme))
    lines.append(f"/// - R{len(spec.rules) + 1} everything else → eager (fail closed).")
    lines += [
        "ResourceResolution resolveResource(",
        "  ResourceIndex index,",
        "  ResourceIndex_Entry entry,",
        "  ResourceResolutionContext context,",
        ") {",
        "  final id = entry.resourceId;",
        "",
    ]
    body: list[str] = []
    for rule in spec.rules:
        body.extend(_rule_body(rule, scheme))
    lines.extend(f"  {statement}" for statement in body)
    lines += [
        "",
        f"  // R{len(spec.rules) + 1}: default — fail closed toward availability.",
        "  return ResourceResolution.eager;",
        "}",
    ]
    return "\n".join(lines)


def _codegen_resolution(spec: ResolutionSpec) -> None:
    header = HEADER_PATH.read_text(encoding="utf-8").rstrip("\n") + "\n"
    imports = sorted({field.import_ for field in spec.context if field.import_ is not None})
    parts = [header]
    if imports:
        parts.append("".join(f'import "{import_}";\n' for import_ in imports) + "\n")
    parts.append(_ENUM_TEMPLATE)
    parts.append(f"\n{_VERSION_DOC}const int kResourceResolutionSchemaVersion = {spec.version};\n")
    parts.append("\n" + _context_class(spec) + "\n")
    parts.append("\n" + _resolve_function(spec) + "\n")
    RESOLUTION_OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    RESOLUTION_OUT_PATH.write_text("".join(parts), encoding="utf-8")


def _codegen_vocabulary(spec: ResolutionSpec) -> None:
    vocab = spec.vocabulary

    legacy_db_id = f"{vocab.scheme}{vocab.legacy_localization_db}"
    locales_prefix = f"{vocab.scheme}{vocab.localization_locales_prefix}"
    images_prefix = f"{vocab.scheme}{vocab.static_images_prefix}"
    models_prefix = f"{vocab.scheme}{vocab.static_models_prefix}"
    placeholder = "{" + vocab.locale_placeholder + "}"
    locale_db_pattern = f"{locales_prefix}{placeholder}.db"

    VOCABULARY_OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    with VOCABULARY_OUT_PATH.open("w", encoding="utf-8") as f:
        f.write(
            f"{_GENERATED_BY}\n"
            "/// URI scheme prefix of checkout resource ids.\n"
            f'const String kResourceIdScheme = "{vocab.scheme}";\n\n'
            "/// Path (relative to `resource://`) of the legacy combined\n"
            "/// localization database.\n"
            f'const String kLegacyLocalizationDbPath = "{vocab.legacy_localization_db}";\n\n'
            "/// Resource id of the legacy combined localization database.\n"
            f'const String kLegacyLocalizationDbResourceId = "{legacy_db_id}";\n\n'
            "/// Path prefix (relative to `resource://`) of the per-locale\n"
            "/// localization databases.\n"
            "const String kLocalizationLocalesPathPrefix = "
            f'"{vocab.localization_locales_prefix}";\n\n'
            "/// Resource-id prefix of the per-locale localization databases.\n"
            f'const String kLocalizationLocalesResourcePrefix = "{locales_prefix}";\n\n'
            "/// Path prefix (relative to `resource://`) of the static image\n"
            "/// resources.\n"
            f'const String kStaticImagesPathPrefix = "{vocab.static_images_prefix}";\n\n'
            "/// Resource-id prefix of the static image resources.\n"
            f'const String kStaticImagesResourcePrefix = "{images_prefix}";\n\n'
            "/// Path prefix (relative to `resource://`) of the static 3D model\n"
            "/// resources.\n"
            f'const String kStaticModelsPathPrefix = "{vocab.static_models_prefix}";\n\n'
            "/// Resource-id prefix of the static 3D model resources.\n"
            f'const String kStaticModelsResourcePrefix = "{models_prefix}";\n\n'
            "/// Resolution-context placeholder embedded in resource-id patterns.\n"
            f'const String kLocalePlaceholder = "{placeholder}";\n\n'
            "/// Resource-id pattern of the per-locale localization database for\n"
            "/// the resolution context's locale.\n"
            "const String kLocaleLocalizationDbResourcePattern = "
            f'"{locale_db_pattern}";\n'
        )


def codegen_dart() -> list[Path]:
    spec = resolution_spec()
    _codegen_resolution(spec)
    _codegen_vocabulary(spec)
    return [RESOLUTION_OUT_PATH, VOCABULARY_OUT_PATH]
